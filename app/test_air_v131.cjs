'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync(__dirname+'/simulateur.html','utf8');
const source=html.split('<script>')[1].split('window.CombatCore=')[0]+html.match(/window\.CombatCore=\{[^;]+;/)[0];
const ctx={window:{},console};vm.createContext(ctx);vm.runInContext(source,ctx);const C=ctx.window.CombatCore;
const s=C.createCombat(),a=C.addFighter(s,'Air'),b=C.addFighter(s,'Ennemi');
const act={id:'reed131',round:s.round,sourceId:a,targetId:b,name:'Souple comme un roseau',approach:'esquiver',options:{airReedConfirmed:true,airReedPrediction:'attaquer'}};
s.actions.push(act);const effects=C.propose(s,act);assert.equal(effects.length,2);
assert.equal(effects[0].amount,2);assert.equal(s.temporaryEffects.length,0);
assert.throws(()=>C.commit(s,{[effects[0].id]:false}),/ensemble/);
assert.equal(s.temporaryEffects.length,0);
C.commit(s);assert.equal(C.fighter(s,a).fatigue,2);assert.equal(s.temporaryEffects.length,1);
assert.equal(s.temporaryEffects[0].reedPrediction,'attaquer');
C.undo(s);assert.equal(s.temporaryEffects.length,0);assert.equal(C.fighter(s,a).fatigue,0);
C.commit(s);s.phase='fin';C.nextRound(s);assert.equal(s.temporaryEffects.length,1);
s.phase='fin';C.nextRound(s);assert.equal(s.temporaryEffects.length,0);
const bad={...act,id:'bad131',options:{airReedConfirmed:true,airReedPrediction:'invalide'}};
assert.throws(()=>C.propose(s,bad),/approche valide/);
console.log('OK V1.31 : Souple comme un roseau, coût, pari, atomicité, annulation, expiration');
