const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync(__dirname+'/simulateur.html','utf8');
const source=html.split('<script>')[1].split('window.CombatCore=')[0]+html.match(/window\.CombatCore=\{[^;]+;/)[0];
const ctx={window:{},console};vm.createContext(ctx);vm.runInContext(source,ctx);
const C=ctx.window.CombatCore,s=C.createCombat();
C.addSceneNote(s,'Première note');C.renameScene(s,'Chapitre deux');C.addSceneNote(s,'=2+2');
const before=JSON.stringify(s),csv=C.exportSceneJournalCSV(s);
assert(csv.startsWith('\uFEFF'));assert(csv.includes('"Scène";"Titre";"Passe";"Note"'));
assert(csv.includes('"\'=2+2"'));assert(csv.includes('"Première note"'));
assert(!C.exportSceneJournalCSV(s,'all','absent').includes('Première note'));
assert(C.exportSceneJournalCSV(s,1,'première').includes('Première note'));
assert(!C.exportSceneJournalCSV(s,2).includes('Première note'));
assert.equal(JSON.stringify(s),before);
assert.throws(()=>C.exportSceneJournalCSV(s,-1),/Filtre/);
console.log('OK export CSV : filtres, neutralisation formule, UTF-8, sans mutation');
