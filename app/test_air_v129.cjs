'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync(__dirname+'/simulateur.html','utf8');
const source=html.split('<script>')[1].split('window.CombatCore=')[0]+html.match(/window\.CombatCore=\{[^;]+;/)[0];
const ctx={window:{},console};vm.createContext(ctx);vm.runInContext(source,ctx);const C=ctx.window.CombatCore;
const s=C.createCombat(),a=C.addFighter(s,'Air'),b=C.addFighter(s,'Cible');
const action={id:'armor129',round:s.round,sourceId:a,targetId:b,name:'Amortir le poing rageur',approach:'esquiver',options:{airCushionArmorConfirmed:true}};
s.actions.push(action);const effects=C.propose(s,action);
assert.equal(s.temporaryEffects.length,0,'Pas de repère avant approbation');
assert.throws(()=>C.commit(s,{[effects[0].id]:false}),/ensemble/);
assert.equal(s.temporaryEffects.length,0,'Refus partiel sans effet');
C.commit(s);assert.equal(s.temporaryEffects.length,1);
assert.equal(s.temporaryEffects[0].expiresAfterRound,2);
assert.equal(s.temporaryEffects[0].originActionId,action.id);
C.undo(s);assert.equal(s.temporaryEffects.length,0,'Annulation retire le repère');
C.commit(s);assert.equal(s.temporaryEffects.length,1);
s.phase='fin';C.nextRound(s);assert.equal(s.round,2);assert.equal(s.temporaryEffects.length,1,'Protection durant la passe suivante');
s.phase='fin';C.nextRound(s);assert.equal(s.round,3);assert.equal(s.temporaryEffects.length,0,'Expiration à la fin de la passe suivante');
console.log('OK V1.29 : création après approbation, refus, annulation, durée exacte');
