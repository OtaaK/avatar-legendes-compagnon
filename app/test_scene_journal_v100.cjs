const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync(__dirname+'/simulateur.html','utf8');
const source=html.split('<script>')[1].split('window.CombatCore=')[0]+html.match(/window\.CombatCore=\{[^;]+;/)[0];
const ctx={window:{},console};vm.createContext(ctx);vm.runInContext(source,ctx);const C=ctx.window.CombatCore;
const s=C.createCombat();const id=C.addSceneNote(s,'  Une lettre mystérieuse  ');
assert.equal(id,'scene-note-1');assert.equal(s.sceneJournal[0].text,'Une lettre mystérieuse');assert.equal(s.history.at(-1).events[0].kind,'scene_note');
for(const bad of ['', '  ', 'x'.repeat(1001),null])assert.throws(()=>C.addSceneNote(s,bad));
C.undo(s);assert.equal(s.sceneJournal.length,0);assert.equal(s.seq,1);
C.addSceneNote(s,'Première scène');C.newScene(s);assert.equal(s.sceneJournal.length,1);assert.equal(s.sceneJournal[0].scene,1);
C.addSceneNote(s,'Deuxième scène');assert.equal(s.sceneJournal[1].scene,2);C.undo(s);assert.equal(s.sceneJournal.length,1);
s.proposals.push({id:'pending'});assert.throws(()=>C.addSceneNote(s,'Interdit'));
console.log('OK : journal narratif, validation, historique, scène, annulation et propositions');
