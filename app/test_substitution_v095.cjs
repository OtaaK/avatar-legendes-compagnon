const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync(__dirname+'/simulateur.html','utf8');
const source=html.split('<script>')[1].split('window.CombatCore=')[0]+html.match(/window\.CombatCore=\{[^;]+;/)[0];
const ctx={window:{},console};vm.createContext(ctx);vm.runInContext(source,ctx);const C=ctx.window.CombatCore;
const s=C.createCombat(),a=C.addFighter(s,'Inventrice','PNJ'),b=C.addFighter(s,'Cible','PNJ');
const me=C.fighter(s,a);me.materials=3;
const entry={famille:'technologie'};
const action={id:'sub1',sourceId:a,targetId:b,name:'Maintenance',options:{catalogEntry:entry,maintenanceCondition:'Confus',materialsInsteadOfFatigue:1}};
me.conditions.push('Confus');
const events=C.propose(s,action);
assert.equal(events.filter(e=>e.kind==='materials_spend').length,1);
assert.equal(events.some(e=>e.kind==='fatigue'&&e.targetId===a),false);
assert.equal(me.materials,3);assert.equal(me.fatigue,0);
assert.equal(C.previewCommit(s).some(e=>e.kind==='materials_spend'),true);
assert.equal(me.materials,3);
C.commit(s);
assert.equal(C.fighter(s,a).materials,5);assert.equal(C.fighter(s,a).fatigue,0);
C.undo(s);assert.equal(C.fighter(s,a).materials,3);assert.equal(C.fighter(s,a).conditions.includes('Confus'),true);
const bad={...action,id:'sub2',options:{...action.options,materialsInsteadOfFatigue:2}};
assert.throws(()=>C.propose(s,bad),/plus de matériels que de fatigue/);
const wrong={...action,id:'sub3',options:{...action.options,catalogEntry:{famille:'universelle'}}};
assert.throws(()=>C.propose(s,wrong),/réservée/);
