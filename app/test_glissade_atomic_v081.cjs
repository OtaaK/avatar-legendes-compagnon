'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync(__dirname+'/simulateur.html','utf8');
const source=html.split('<script>')[1].split('window.CombatCore=')[0] + html.match(/window\.CombatCore=\{[^;]+;/)[0];
const ctx={window:{},console};vm.createContext(ctx);vm.runInContext(source,ctx);
const C=ctx.window.CombatCore;
const s=C.createCombat(),a=C.addFighter(s,'A'),b=C.addFighter(s,'B'),c=C.addFighter(s,'C');
C.setEngagement(s,a,b,true);C.setEngagement(s,b,c,true);
const act={id:'glissade-test',sourceId:a,targetId:b,name:'Glissade',options:{glissadeEnemies:[b],glissadeNewEngagements:[[a,b]]}};
const effects=C.propose(s,act);
const terrain=effects.filter(e=>['engage','disengage'].includes(e.kind));
assert.equal(terrain.length,1,'conservation A-B, rupture B-C');
// Deux changements réels : enlever B-C et créer A-C (avec C déplacé).
const s2=C.createCombat(),p=C.addFighter(s2,'P'),q=C.addFighter(s2,'Q'),r=C.addFighter(s2,'R'),t=C.addFighter(s2,'T');
C.setEngagement(s2,q,r,true);
const act2={id:'glissade-2',sourceId:p,targetId:q,name:'Glissade',options:{glissadeEnemies:[q],glissadeNewEngagements:[[q,t]]}};
const es=C.propose(s2,act2);const links=es.filter(e=>['engage','disengage'].includes(e.kind));
assert.equal(links.length,2);
const rejectOne={[links[0].id]:false};
const before=JSON.stringify(s2);
assert.throws(()=>C.previewCommit(s2,rejectOne),/valider ou refuser ensemble/);
assert.throws(()=>C.commit(s2,rejectOne),/valider ou refuser ensemble/);
assert.equal(JSON.stringify(s2),before,'aucune mutation après refus partiel');
const rejectBoth=Object.fromEntries(links.map(e=>[e.id,false]));
C.commit(s2,rejectBoth);assert(C.isEngaged(s2,q,r));assert(!C.isEngaged(s2,q,t));
assert(C.undo(s2));assert.equal(JSON.stringify(s2.engagements),JSON.stringify([[q,r]]));
const s3=C.createCombat(),x=C.addFighter(s3,'X'),y=C.addFighter(s3,'Y'),z=C.addFighter(s3,'Z');
C.setEngagement(s3,y,z,true);
C.propose(s3,{id:'g3',sourceId:x,targetId:y,name:'Glissade',options:{glissadeEnemies:[y],glissadeNewEngagements:[[x,y]]}});
C.commit(s3,{});assert(!C.isEngaged(s3,y,z));assert(C.isEngaged(s3,x,y));
assert(C.undo(s3));assert(C.isEngaged(s3,y,z));assert(!C.isEngaged(s3,x,y));
console.log('V0.81: validation atomique Glissade OK');
