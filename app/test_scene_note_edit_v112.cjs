const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync(__dirname+'/simulateur.html','utf8');
const source=html.split('<script>')[1].split('window.CombatCore=')[0]+html.match(/window\.CombatCore=\{[^;]+;/)[0];
const ctx={window:{},console};vm.createContext(ctx);vm.runInContext(source,ctx);
const C=ctx.window.CombatCore,s=C.createCombat();
const id=C.addSceneNote(s,'  Première note  ');
const before=JSON.stringify(s);
assert.equal(C.editSceneNote(s,id,'Première note'),false);
assert.equal(JSON.stringify(s),before);
assert.throws(()=>C.editSceneNote(s,id,'  '),/1 à 1000/);
assert.throws(()=>C.editSceneNote(s,'scene-note-999','X'),/introuvable/);
assert.equal(C.editSceneNote(s,id,'Note corrigée'),true);
assert.equal(s.sceneJournal[0].text,'Note corrigée');
assert.equal(C.undo(s),true);
assert.equal(s.sceneJournal[0].text,'Première note');
assert.equal(C.removeSceneNote(s,id),true);
assert.equal(s.sceneJournal.length,0);
assert.equal(C.undo(s),true);
assert.equal(s.sceneJournal[0].id,id);
s.proposals.push({id:'pending'});
const blocked=JSON.stringify(s);
assert.throws(()=>C.editSceneNote(s,id,'Non'),/propositions/);
assert.throws(()=>C.removeSceneNote(s,id),/propositions/);
assert.equal(JSON.stringify(s),blocked);
console.log('V1.12 : édition, suppression, validation, no-op, undo et propositions OK');
