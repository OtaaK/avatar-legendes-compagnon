const fs=require('fs'),vm=require('vm'),assert=require('assert');
const html=fs.readFileSync(__dirname+'/simulateur.html','utf8');
const source=html.split('<script>')[1].split('window.CombatCore=')[0]+html.match(/window\.CombatCore=\{[^;]+;/)[0];
const ctx={window:{},console};vm.createContext(ctx);vm.runInContext(source,ctx);const C=ctx.window.CombatCore;
const s=C.createCombat(),a=C.addFighter(s,'Maître'),b=C.addFighter(s,'Cible');
const master=C.fighter(s,a),target=C.fighter(s,b);
target.statuses.push('gene');s.temporaryEffects.push({id:'metal1',originLabel:'Entraves de métal',originSourceId:a,targetId:b,metalGrantedAdvantage:false,metalExternalAdvantage:false});
C.setEngagement(s,a,b,true);assert(master.statuses.includes('avantage'),'Engagement active Avantagé');
C.setEngagement(s,a,b,false);assert(!master.statuses.includes('avantage'),'Désengagement retire Avantagé');
C.setEngagement(s,a,b,true);assert(master.statuses.includes('avantage'));
C.removeTemporaryEffect(s,'metal1');assert(!master.statuses.includes('avantage'),'Libération retire Avantagé');assert(!target.statuses.includes('gene'),'Libération retire Gêné');
C.undo(s);assert(C.fighter(s,a).statuses.includes('avantage'),'Annulation restaure Avantagé');
console.log('V1.93 Entraves de métal : OK');
