const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync(require('../support/paths.cjs').APP_HTML,'utf8');
const source=html.split('<script>')[1].split('window.CombatCore=')[0]+html.match(/window\.CombatCore=\{[^;]+;/)[0];
const ctx={window:{},console};vm.createContext(ctx);vm.runInContext(source,ctx);
const C=ctx.window.CombatCore,s=C.createCombat();
const first=C.addSceneNote(s,'Une note');
assert.equal(s.sceneJournal[0].id,first);
assert.equal(C.undo(s),true);
assert.equal(s.sceneJournal.length,0);
assert.equal(C.addSceneNote(s,'Une note'),first,'identifiant restauré après annulation');
const placeholder=s.sceneJournal[0];
s.sceneJournal=Array(100000).fill(placeholder);
const beforeSeq=s.seq,beforeHistory=s.history.length,beforeSnapshots=s.snapshots.length;
assert.throws(()=>C.addSceneNote(s,'Refus'),/100 000 notes/);
assert.equal(s.seq,beforeSeq);
assert.equal(s.sceneJournal.length,100000);
assert.equal(s.history.length,beforeHistory);
assert.equal(s.snapshots.length,beforeSnapshots);
console.log('V1.13 : plafond du journal, atomicité, identifiants et annulation OK');
